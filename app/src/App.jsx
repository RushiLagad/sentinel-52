import { useEffect, useMemo, useState } from "react";
import { useAppData } from "./lib/data.js";
import CurrentRiskView from "./components/CurrentRiskView.jsx";
import AlertQueue from "./components/AlertQueue.jsx";
import ScenarioBuilder from "./components/ScenarioBuilder.jsx";
import RecommendedActionPanel from "./components/RecommendedActionPanel.jsx";
import EvidencePanel from "./components/EvidencePanel.jsx";
import EquityView from "./components/EquityView.jsx";
import SyntheticBadge from "./components/SyntheticBadge.jsx";

const SECTIONS = [["risk", "Current risk"], ["alerts", "Alerts"], ["scenarios", "Scenarios"], ["actions", "Actions"], ["equity", "Equity"], ["evidence", "Evidence"]];

function useHashRoute() {
  const [h, setH] = useState(() => window.location.hash.replace(/^#\/?/, "") || "risk");
  useEffect(() => { const f = () => setH(window.location.hash.replace(/^#\/?/, "") || "risk"); window.addEventListener("hashchange", f); return () => window.removeEventListener("hashchange", f); }, []);
  useEffect(() => { document.getElementById(h)?.scrollIntoView({ block: "start" }); }, [h]);
  useEffect(() => {
    const els = SECTIONS.map(([id]) => document.getElementById(id)).filter(Boolean);
    if (!els.length || !("IntersectionObserver" in window)) return;
    const io = new IntersectionObserver((entries) => {
      const vis = entries.filter((e) => e.isIntersecting).sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (vis) setH(vis.target.id);
    }, { rootMargin: "-40% 0px -50% 0px", threshold: [0, 0.2, 0.5] });
    els.forEach((el) => io.observe(el));
    return () => io.disconnect();
  });
  return h;
}

function useTheme() {
  const [t, setT] = useState(() => { try { return localStorage.getItem("s52-theme") || ""; } catch { return ""; } });
  useEffect(() => { if (t) document.documentElement.setAttribute("data-theme", t); else document.documentElement.removeAttribute("data-theme"); try { localStorage.setItem("s52-theme", t); } catch {} }, [t]);
  return [t, setT];
}

export default function App() {
  const { status, data, error } = useAppData();
  const route = useHashRoute();
  const [theme, setTheme] = useTheme();
  const [picked, setPicked] = useState(null);
  const [scenario, setScenario] = useState(null);
  const names = useMemo(() => data ? Object.fromEntries(data.actions.lots.map((l) => [l.establishment_id, l.establishment_name])) : {}, [data]);
  useEffect(() => { if (data && !scenario) setScenario(data.actions.meta.default_scenario); }, [data, scenario]);

  if (status === "loading") return <main><p className="muted">Loading data…</p></main>;
  if (status === "error") return <main><p className="notice">Could not load the data files: {error}. Build them with <code>python analysis/scripts/17_build_app_data.py --out app/public/data</code>.</p></main>;
  const meta = data.meta;
  return (
    <>
      <header className="topbar">
        <h1>Sentinel-52</h1>
        <span className="muted small">a regional food bank's view of FSIS-regulated poultry · reorders attention, does not adjudicate</span>
        <nav>{SECTIONS.map(([id, label]) => <a key={id} href={`#/${id}`} className={route === id ? "active" : ""}>{label}</a>)}</nav>
        <span className="spacer" />
        <button className="theme-btn" onClick={() => setTheme(theme === "dark" ? "light" : "dark")}>{theme === "dark" ? "light" : "dark"} mode</button>
      </header>
      <main>
        <p className="notice"><b>The inventory is simulated.</b> Lots, pounds, destinations and shelf life are generated by a seeded procedure and carry the <SyntheticBadge /> mark wherever they appear. Risk scores, FSIS categories, recalls and outcomes are real public data. {meta.restrictions?.[1]}</p>
        <CurrentRiskView risk={data.current_risk} names={names} onPick={(k) => setPicked(picked === k ? null : k)} picked={picked} />
        <AlertQueue alerts={data.alerts} names={names} />
        <ScenarioBuilder scenarios={data.scenarios} equity={data.equity} selected={scenario} onSelect={setScenario} />
        <RecommendedActionPanel actions={data.actions} picked={picked} />
        <EquityView equity={data.equity} selected={scenario} />
        <EvidencePanel evidence={data.evidence} burden={data.burden} meta={meta} />
        <footer>
          Data built {meta.generated_utc} by <code>17_build_app_data.py</code>, schema {meta.schema_version}. Sources listed under Evidence with file hashes. Provenance in <code>data/PROVENANCE.md</code>, every column in <code>data/DATA_DICTIONARY.md</code>. NAFSI Hub Student Data Challenge, Fall 2026, SENS-D — Sentinel-52.
        </footer>
      </main>
    </>
  );
}
