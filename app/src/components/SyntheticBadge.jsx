// Not decoration. This is the mechanism that keeps the simulated inventory from
// being read as real. It goes on every pounds- or meals-denominated figure.
export default function SyntheticBadge({ title }) {
  return (
    <span className="badge synthetic" title={title || "Simulated inventory: lots, pounds, destinations and shelf life are generated by 14_build_synthetic_inventory.py. Not a measurement of a real food bank."}>
      SIMULATED
    </span>
  );
}
